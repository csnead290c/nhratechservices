#!/usr/bin/env node
/**
 * Safe CLI Migration Runner for v36 Rules Committees
 *
 * Requirements:
 *   - CLI-only execution
 *   - Requires --apply flag to make changes (default is dry-run)
 *   - Uses production api/config.php for DB credentials (preferred)
 *   - Falls back to env vars if local/production detection fails
 *   - Idempotent (safe to run multiple times)
 *   - No destructive SQL (no DROP, TRUNCATE, DELETE against committee tables)
 *   - Does not seed sample committees
 *
 * Usage:
 *   # Check status only (dry-run, no changes)
 *   node scripts/migrations/run-v36-rules-committees.mjs
 *
 *   # Apply migration
 *   node scripts/migrations/run-v36-rules-committees.mjs --apply
 */

import { spawn } from 'child_process';
import { fileURLToPath } from 'url';
import { dirname, resolve } from 'path';
import { existsSync } from 'fs';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);

const PROJECT_ROOT = resolve(__dirname, '../..');
const SHARED_MIGRATION = resolve(PROJECT_ROOT, 'api/migrations/v36-rules-committees.php');

// Parse arguments
const args = process.argv.slice(2);
const APPLY = args.includes('--apply');
const DRY_RUN = !APPLY;

console.log('=== v36 Rules Committees Migration Runner ===\n');
console.log(`Mode: ${DRY_RUN ? 'DRY-RUN (status check only)' : 'APPLY (will modify database)'}`);

if (!APPLY) {
  console.log('\nTo apply the migration, run with --apply flag:\n  node scripts/migrations/run-v36-rules-committees.mjs --apply\n');
}

// Validate shared migration file exists
if (!existsSync(SHARED_MIGRATION)) {
  console.error(`ERROR: Shared migration not found: ${SHARED_MIGRATION}`);
  process.exit(1);
}

/**
 * Run PHP CLI with the migration
 */
async function runMigration() {
  // Create temporary CLI script
  const cliScriptContent = `<?php
/**
 * CLI Entry Point for v36 Migration
 * Auto-generated by run-v36-rules-committees.mjs
 */

// Parse command line arguments
$dryRun = in_array('--dry-run', $argv) || !in_array('--apply', $argv);

// Load dependencies
require_once __DIR__ . '/../../config.php';
require_once __DIR__ . '/../../functions.php';
require_once __DIR__ . '/v36-rules-committees.php';

// CLI context - no web auth required, but verify we're actually in CLI
if (php_sapi_name() !== 'cli') {
    fwrite(STDERR, "ERROR: This script must be run from CLI\\n");
    exit(1);
}

// Get database connection
$pdo = getDB();

// Run migration
$result = v36MigrateRulesCommittees($pdo, $dryRun);

// Output results
foreach ($result['messages'] as $msg) {
    echo $msg . "\\n";
}

if (!empty($result['errors'])) {
    fwrite(STDERR, "\\nERRORS:\\n");
    foreach ($result['errors'] as $err) {
        fwrite(STDERR, "  ✗ " . $err . "\\n");
    }
}

// Get final counts
$counts = v36GetCommitteeTableCounts($pdo);
echo "\\nFinal counts:\n";
echo "  rules_committees:      " . $counts['rules_committees'] . " rows\\n";
echo "  committee_memberships: " . $counts['committee_memberships'] . " rows\\n";

// Exit with error code if there were errors
exit(empty($result['errors']) ? 0 : 1);
`;

  // Write temporary CLI script
  const fs = await import('fs');
  const cliScriptPath = resolve(PROJECT_ROOT, 'api/migrations/v36-rules-committees-cli.php');

  try {
    fs.writeFileSync(cliScriptPath, cliScriptContent);
  } catch (err) {
    console.error(`ERROR: Failed to create CLI script: ${err.message}`);
    process.exit(1);
  }

  // Determine execution method
  let phpPath = process.env.PHP_PATH || 'php';
  let scriptToRun = cliScriptPath;
  let envVars = { ...process.env };

  // Local execution
  console.log(`\nExecuting: ${phpPath} ${scriptToRun} ${DRY_RUN ? '--dry-run' : '--apply'}\n`);

  return new Promise((resolve, reject) => {
    const proc = spawn(phpPath, [scriptToRun, DRY_RUN ? '--dry-run' : '--apply'], {
      cwd: PROJECT_ROOT,
      env: envVars,
      stdio: 'inherit',
    });

    proc.on('close', (code) => {
      // Clean up temporary CLI script
      try {
        fs.unlinkSync(cliScriptPath);
      } catch {}

      if (code === 0) {
        resolve();
      } else {
        reject(new Error(`PHP process exited with code ${code}`));
      }
    });

    proc.on('error', (err) => {
      // Clean up temporary CLI script
      try {
        fs.unlinkSync(cliScriptPath);
      } catch {}

      reject(err);
    });
  });
}

// Main execution
runMigration()
  .then(() => {
    console.log('\n=== Migration runner completed ===');
    process.exit(0);
  })
  .catch((err) => {
    console.error(`\nERROR: ${err.message}`);
    process.exit(1);
  });
