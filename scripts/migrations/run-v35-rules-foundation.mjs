#!/usr/bin/env node
/**
 * Safe CLI Migration Runner for v35 Rules Foundation
 * 
 * Requirements:
 *   - CLI-only execution
 *   - Requires --apply flag to make changes (default is dry-run)
 *   - Uses production api/config.php for DB credentials (preferred)
 *   - Falls back to env vars if local/production detection fails
 *   - Idempotent (safe to run multiple times)
 *   - No destructive SQL (no DROP, TRUNCATE, DELETE against rules tables)
 *   - Does not import sample rules
 * 
 * Usage:
 *   # Check status only (dry-run, no changes)
 *   node scripts/migrations/run-v35-rules-foundation.mjs
 * 
 *   # Apply migration
 *   node scripts/migrations/run-v35-rules-foundation.mjs --apply
 * 
 *   # With explicit PHP path
 *   PHP_PATH=/usr/bin/php node scripts/migrations/run-v35-rules-foundation.mjs --apply
 */

import { spawn } from 'child_process';
import { fileURLToPath } from 'url';
import { dirname, resolve } from 'path';
import { existsSync } from 'fs';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);

const PROJECT_ROOT = resolve(__dirname, '../..');
const PHP_SCRIPT = resolve(PROJECT_ROOT, 'api/migrations/v35-rules-foundation-cli.php');
const SHARED_MIGRATION = resolve(PROJECT_ROOT, 'api/migrations/v35-rules-foundation.php');

// Parse arguments
const args = process.argv.slice(2);
const APPLY = args.includes('--apply');
const DRY_RUN = !APPLY;

// Environment detection
const IS_PRODUCTION_SSH = process.env.NHRATS_PRODUCTION_SSH === 'true';
const PRODUCTION_PHP_PATH = process.env.NHRATS_PRODUCTION_PHP || 'php';
const PRODUCTION_DOCROOT = process.env.NHRATS_PRODUCTION_DOCROOT || '/home/customer/www/nhratechservices.com/public_html';

console.log('=== v35 Rules Foundation Migration Runner ===\n');
console.log(`Mode: ${DRY_RUN ? 'DRY-RUN (status check only)' : 'APPLY (will modify database)'}`);

if (!APPLY) {
  console.log('\nTo apply the migration, run with --apply flag:\n  node scripts/migrations/run-v35-rules-foundation.mjs --apply\n');
}

// Validate shared migration file exists
if (!existsSync(SHARED_MIGRATION)) {
  console.error(`ERROR: Shared migration not found: ${SHARED_MIGRATION}`);
  process.exit(1);
}

/**
 * Run PHP CLI with the migration
 */
async function runMigration() {
  // Create temporary CLI script if it doesn't exist
  const cliScriptContent = `<?php
/**
 * CLI Entry Point for v35 Migration
 * Auto-generated by run-v35-rules-foundation.mjs
 */

// Parse command line arguments
$dryRun = in_array('--dry-run', $argv) || !in_array('--apply', $argv);

// Load dependencies
require_once __DIR__ . '/../../config.php';
require_once __DIR__ . '/../../functions.php';
require_once __DIR__ . '/v35-rules-foundation.php';

// CLI context - no web auth required, but verify we're actually in CLI
if (php_sapi_name() !== 'cli') {
    fwrite(STDERR, "ERROR: This script must be run from CLI\\n");
    exit(1);
}

// Get database connection
$pdo = getDB();

// Run migration
$result = v35MigrateRulesFoundation($pdo, $dryRun);

// Output results
foreach ($result['messages'] as $msg) {
    echo $msg . "\\n";
}

if (!empty($result['errors'])) {
    fwrite(STDERR, "\\nERRORS:\\n");
    foreach ($result['errors'] as $err) {
        fwrite(STDERR, "  ✗ " . $err . "\\n");
    }
}

// Get final counts
$counts = v35GetRulesTableCounts($pdo);
echo "\\nFinal counts:\n";
echo "  rules:         " . $counts['rules'] . " rows\\n";
echo "  rule_versions: " . $counts['rule_versions'] . " rows\\n";

// Exit with error code if there were errors
exit(empty($result['errors']) ? 0 : 1);
`;

  // Write temporary CLI script
  const fs = await import('fs');
  const cliScriptPath = resolve(PROJECT_ROOT, 'api/migrations/v35-rules-foundation-cli.php');
  
  try {
    fs.writeFileSync(cliScriptPath, cliScriptContent);
  } catch (err) {
    console.error(`ERROR: Failed to create CLI script: ${err.message}`);
    process.exit(1);
  }

  // Determine execution method
  let phpPath = process.env.PHP_PATH || 'php';
  let scriptToRun = cliScriptPath;
  let envVars = { ...process.env };

  // If production SSH is configured, use that
  if (IS_PRODUCTION_SSH) {
    console.log('\nUsing production SSH execution...');
    return runViaSSH(cliScriptPath);
  }

  // Local execution
  console.log(`\nExecuting: ${phpPath} ${scriptToRun} ${DRY_RUN ? '--dry-run' : '--apply'}\n`);

  return new Promise((resolve, reject) => {
    const proc = spawn(phpPath, [scriptToRun, DRY_RUN ? '--dry-run' : '--apply'], {
      cwd: PROJECT_ROOT,
      env: envVars,
      stdio: 'inherit',
    });

    proc.on('close', (code) => {
      // Clean up temporary CLI script
      try {
        fs.unlinkSync(cliScriptPath);
      } catch {}
      
      if (code === 0) {
        resolve();
      } else {
        reject(new Error(`PHP process exited with code ${code}`));
      }
    });

    proc.on('error', (err) => {
      // Clean up temporary CLI script
      try {
        fs.unlinkSync(cliScriptPath);
      } catch {}
      
      reject(err);
    });
  });
}

/**
 * Run migration via SSH to production
 */
async function runViaSSH(cliScriptPath) {
  const { exec } = await import('child_process');
  const fs = await import('fs');
  
  const sshHost = process.env.NHRATS_SSH_HOST || 'ssh.nhratechservices.com';
  const sshPort = process.env.NHRATS_SSH_PORT || '18765';
  const sshUser = process.env.NHRATS_SSH_USER || 'u3542-cpixgw37zfgv';
  
  console.log(`  SSH: ${sshUser}@${sshHost}:${sshPort}`);
  console.log(`  Docroot: ${PRODUCTION_DOCROOT}`);
  
  // Read the CLI script content
  const scriptContent = fs.readFileSync(cliScriptPath, 'utf8');
  
  // Clean up local temp file
  try {
    fs.unlinkSync(cliScriptPath);
  } catch {}
  
  // Escape the script content for SSH
  const escapedScript = scriptContent.replace(/'/g, "'\\''");
  
  // Build SSH command
  const sshCmd = `ssh -p ${sshPort} -o StrictHostKeyChecking=no ${sshUser}@${sshHost} 'cd ${PRODUCTION_DOCROOT}/api/migrations && php -r '${escapedScript}' ${DRY_RUN ? '--dry-run' : '--apply'}'`;
  
  return new Promise((resolve, reject) => {
    exec(sshCmd, (error, stdout, stderr) => {
      if (stdout) console.log(stdout);
      if (stderr) console.error(stderr);
      
      if (error) {
        reject(error);
      } else {
        resolve();
      }
    });
  });
}

// Main execution
runMigration()
  .then(() => {
    console.log('\n=== Migration runner completed ===');
    process.exit(0);
  })
  .catch((err) => {
    console.error(`\nERROR: ${err.message}`);
    process.exit(1);
  });
